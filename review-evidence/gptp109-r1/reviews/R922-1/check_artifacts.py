#!/usr/bin/env python3
"""Verify exact tracked bytes, generated images, arithmetic and public receipts."""
import argparse
import hashlib
import importlib
import json
import os
from pathlib import Path
import random
import re
import stat
import subprocess
import sys

HEAD='8e4889bba462d14d4e5a34068769872510d4775d'
BASE='1213ac5b9e09b8759ba76cc70c53652b5e108996'
EVIDENCE='90fd6083843178d81423c1e2ade23a95b5dc5d63'
PACKET=Path(__file__).resolve().parent

def git(repo,*args):
    return subprocess.check_output(['rtk','proxy','git',*args],cwd=repo)

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('repo',type=Path)
    args=ap.parse_args()
    repo=args.repo.resolve()
    assert git(repo,'rev-parse','HEAD').decode().strip()==HEAD
    assert git(repo,'rev-parse','HEAD^{tree}').decode().strip()=='bcd69a8e01ba7856d093579faf0dfbf256e772e4'
    entries=git(repo,'ls-tree','-rz',HEAD).split(b'\0')
    count=0
    links=[]
    for entry in entries:
        if not entry: continue
        meta,path=entry.split(b'\t',1)
        mode,kind,oid=meta.decode().split()
        name=os.fsdecode(path)
        if mode=='160000':
            links.append((name,oid))
            continue
        file=repo/name
        raw=os.readlink(file).encode() if mode=='120000' else file.read_bytes()
        digest=hashlib.sha1(b'blob '+str(len(raw)).encode()+b'\0'+raw).hexdigest()
        assert digest==oid, name
        actual='120000' if file.is_symlink() else ('100755' if file.stat().st_mode & stat.S_IXUSR else '100644')
        assert actual==mode,(name,mode,actual)
        count+=1
    assert git(repo,'diff','--cached','--name-only',HEAD)==b''
    assert git(repo,'diff','--name-only',HEAD)==b''
    assert not links
    print(f'Exact head/tree/index PASS; {count} tracked blob bytes and modes PASS; required nested gitlinks: none.')
    print('Status:',git(repo,'status','--porcelain=v1').decode().strip() or 'clean')
    sys.path.insert(0,str(PACKET/'scratch/head/tb/verilator/engine'))
    m=importlib.import_module('mutants')
    assert len(m.MUTATIONS)==175 and len(m.P109_MUTATIONS)==8
    public=PACKET/'scratch/review-evidence/gptp109-r1'
    manifest=json.loads((public/'MANIFEST.json').read_text())
    for row in manifest:
        assert hashlib.sha256((public/row['file']).read_bytes()).hexdigest()==row['published_sha256'],row['file']
    arm=(public/'author/receipts/arm_full.txt').read_text()
    caught=re.findall(r'^\[PASS\] mutant caught: (.*?) - breaks ',arm,re.M)
    assert caught==[x[0] for x in m.MUTATIONS]
    print('Public manifest: all 12 published SHA-256 values PASS; full-arm names/order 175/175 PASS, including eight #109 controls.')
    scratch=PACKET/'scratch/artifact-checks'
    scratch.mkdir(exist_ok=True)
    maps=[]
    for sha in [BASE,HEAD]:
        gen=scratch/(sha[:8]+'.py')
        gen.write_bytes(git(repo,'show',sha+':hdl/ucode/gen_gptp_ucode.py'))
        for name,flags in [('default',[]),('tsngen',['--clk-hz','2000000']),('engine',list(m.GENARGS)),('seed',[*m.GENARGS,'--seq-seed','0x200000'])]:
            out=scratch/(sha[:8]+'-'+name+'.hex')
            result=subprocess.check_output(['rtk','proxy',sys.executable,str(gen),*flags,'-o',str(out)],text=True)
            (PACKET/(sha[:8]+'-'+name+'-generation.log')).write_text(result)
            line=next(x for x in result.splitlines() if 'real (' in x)
            print(sha[:8],name,line.split(': ',1)[1])
            if sha==HEAD:
                targets={'default':['syn/ooc/work/gptp_ucode.hex','tb/verilator/ucpu/gptp_ucode.hex'],'tsngen':['tb/tsngen/gptp_ucode.hex'],'engine':['tb/verilator/engine/gptp_ucode.hex']}.get(name,[])
                for target in targets:
                    assert out.read_bytes()==(repo/target).read_bytes(),target
                    print('Generated bytes PASS:',target)
        maps.append((scratch/(sha[:8]+'-default.hex')).read_text().splitlines())
    assert len(maps[0])==len(maps[1])==1024
    print('ROM changed word addresses:',','.join(str(i) for i,(a,b) in enumerate(zip(*maps)) if a!=b))
    mask=(1<<64)-1
    def signed(x):
        x &= mask
        return x-(1<<64) if x>>63 else x
    rng=random.Random(109)
    values=list(range(-4096,4097))+[-(1<<62),-(1<<62)+1,(1<<62)-1,-(1<<31)-1,-(1<<32),-5000000]
    values += [rng.randrange(-(1<<62),1<<62) for _ in range(100000)]
    for d in values:
        t=signed(d+800)
        used=signed(d-((t&mask)&(t>>63)))
        assert used==max(d,-800)
        good=((signed(used-801)&mask)>>63)==1
        assert good==(d<=800)
        if d<0:
            word=used & 0xffffffff
            assert word>>31 and (0 if word>>31 else word)==0
    print(f'Independent 64-bit arithmetic oracle PASS: {len(values)} vectors, including -2^62, floor and positive threshold boundaries; all negatives publish a negative 32-bit word.')
    source=(repo/'hdl/ucode/gen_gptp_ucode.py').read_text()
    docs=(repo/'docs/INTEGRATION.md').read_text()
    gate=(repo/'scripts/check_docs.py').read_text()
    assert all('NPD_LO_C' not in x for x in [source,docs,gate])
    print('NPD_LO_C retired consistently from generator, integration contract and docs constant gate.')

if __name__=='__main__': main()
